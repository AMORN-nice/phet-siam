# One-off: converts lapidary-ai game.py card/noble lists into server/data.js
import re, sys, json
src = open(sys.argv[1]).read()
cards = []
tiers = src[src.index('tier_1 = ['):src.index('nobles = [')]
for m in re.finditer(r"Card\((\d), '(\w+)', (\d)((?:, \w+=\d)*)\)", tiers):
    tier, color, pts, rest = int(m[1]), m[2], int(m[3]), m[4]
    cost = {c: 0 for c in ['white','blue','green','red','black']}
    for k, v in re.findall(r"(\w+)=(\d)", rest): cost[k] = int(v)
    cards.append({'id': len(cards)+1, 'tier': tier, 'color': color, 'points': pts, 'cost': cost})
nobles = []
block = src[src.index('nobles = ['):]
block = block[:block.index(']')]
for m in re.finditer(r"Noble\(([^)]*)\)", block):
    req = {c: 0 for c in ['white','blue','green','red','black']}
    for k, v in re.findall(r"(\w+)=(\d)", m[1]): req[k] = int(v)
    nobles.append({'id': len(nobles)+1, 'points': 3, 'req': req})
out = "// Card and noble data (game mechanics). Generated by scripts/build-data.py.\n"
out += "const COLORS = ['white', 'blue', 'green', 'red', 'black'];\n"
out += "const CARDS = [\n" + ",\n".join("  " + json.dumps(c) for c in cards) + "\n];\n"
out += "const NOBLES = [\n" + ",\n".join("  " + json.dumps(n) for n in nobles) + "\n];\n"
out += "module.exports = { COLORS, CARDS, NOBLES };\n"
open('server/data.js', 'w').write(out)
print(len(cards), len(nobles))
